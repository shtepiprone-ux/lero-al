const pair = (base, file, allowActor, allowInput, allowResponse, denyActor, denyInput, denyResponse, forbidden) => {
  const inv = unitCases.find((x) => x.id === `SEC-X-SRV-${base}`).invariant
  return [
    c(`SEC-X-INT-${base}-ALLOW`, 'server', 'allow', 'integration', false, inv, allowActor, 'the approved development project',
      allowInput, allowResponse, ['a refusal of the permitted request'], file, `${base.toLowerCase()} allowed on the real project`),
    c(`SEC-X-INT-${base}-DENY`, 'server', 'deny', 'integration', false, inv, denyActor, 'the approved development project',
      denyInput, denyResponse, forbidden, file, `${base.toLowerCase()} refused on the real project`),
  ]
}

