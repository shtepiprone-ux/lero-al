#!/usr/bin/env node
/**
 * audit-listing-visibility.mjs
 *
 * One-time read-only audit: finds every listing whose status is marked
 * publicEligible by the canonical policy but which isListingPubliclyVisible
 * rejects (expired or NULL expires_at).
 *
 * Writes a governance report to docs/governance-reports/.
 * Zero DB writes — read-only query only.
 *
 * Usage: node scripts/audit-listing-visibility.mjs
 *
 * Requires: NEXT_PUBLIC_SUPABASE_URL + SUPABASE_SERVICE_ROLE_KEY in .env.local
 * (runs with service_role to bypass RLS for the audit).
 *
 * This module exports its policy + classifier so the drift-guard test in
 * visibility.test.ts can assert against the ACTUAL script, not a decoy copy.
 * Importing this module does NOT run the audit — execution is gated behind
 * the entry-point check at the bottom.
 */

import { createClient } from '@supabase/supabase-js'
import { writeFileSync, mkdirSync } from 'node:fs'
import { resolve } from 'node:path'
import { config } from 'dotenv'
import { fileURLToPath } from 'node:url'

// Mirror of the canonical policy from src/modules/listings/lib/visibility.ts.
// Drift-guarded: visibility.test.ts imports this export and asserts deep-equal.
export const PUBLIC_VISIBLE_STATUSES = {
  active:   { publicEligible: true,  requiresUnexpired: true },
  inactive: { publicEligible: false, requiresUnexpired: false },
  sold:     { publicEligible: false, requiresUnexpired: false },
  rented:   { publicEligible: false, requiresUnexpired: false },
  archived: { publicEligible: false, requiresUnexpired: false },
  pending:  { publicEligible: false, requiresUnexpired: false },
}

export function classifyHiddenReason(listing) {
  const rule = PUBLIC_VISIBLE_STATUSES[listing.status]
  if (!rule || !rule.publicEligible) return null // not public-eligible → not in scope
  if (listing.expires_at === null) return 'no_expiry'
  if (new Date(listing.expires_at) < new Date()) return 'expired'
  return null // visible → not hidden
}

async function main() {
  config({ path: '.env.local' })

  const SUPABASE_URL = process.env.NEXT_PUBLIC_SUPABASE_URL
  const SUPABASE_KEY = process.env.SUPABASE_SERVICE_ROLE_KEY

  if (!SUPABASE_URL || !SUPABASE_KEY) {
    console.error('Missing NEXT_PUBLIC_SUPABASE_URL or SUPABASE_SERVICE_ROLE_KEY in .env.local')
    process.exit(1)
  }

  const supabase = createClient(SUPABASE_URL, SUPABASE_KEY)

  const eligibleStatuses = Object.entries(PUBLIC_VISIBLE_STATUSES)
    .filter(([, rule]) => rule.publicEligible)
    .map(([status]) => status)

  console.log(`Querying listings with status in [${eligibleStatuses.join(', ')}]...`)

  const { data: listings, error } = await supabase
    .from('listings')
    .select('id, slug, status, expires_at, title')
    .in('status', eligibleStatuses)
    .order('expires_at', { ascending: true, nullsFirst: true })

  if (error) {
    console.error('DB error:', error.message)
    process.exit(1)
  }

  const hidden = []
  for (const listing of listings ?? []) {
    const reason = classifyHiddenReason(listing)
    if (reason) {
      hidden.push({ ...listing, reason })
    }
  }

  const date = new Date().toISOString().slice(0, 10)
  const reportDir = resolve('docs/governance-reports')
  const reportPath = resolve(reportDir, `${date}-public-eligible-but-hidden-listings.md`)

  mkdirSync(reportDir, { recursive: true })

  let report = `# Public-Eligible-but-Hidden Listings Audit\n\n`
  report += `**Date:** ${date}\n`
  report += `**Total public-eligible listings queried:** ${(listings ?? []).length}\n`
  report += `**Hidden (public-eligible but not publicly visible):** ${hidden.length}\n\n`

  if (hidden.length === 0) {
    report += `No public-eligible-but-hidden listings found. All listings with status in [${eligibleStatuses.join(', ')}] are publicly visible.\n`
  } else {
    report += `| # | ID | Slug | Status | expires_at | Reason |\n`
    report += `|---|---|---|---|---|---|\n`
    for (let i = 0; i < hidden.length; i++) {
      const h = hidden[i]
      report += `| ${i + 1} | ${h.id} | ${h.slug ?? '—'} | ${h.status} | ${h.expires_at ?? 'NULL'} | ${h.reason} |\n`
    }
    report += `\n### Summary by reason\n\n`
    const byReason = {}
    for (const h of hidden) {
      byReason[h.reason] = (byReason[h.reason] ?? 0) + 1
    }
    for (const [reason, count] of Object.entries(byReason)) {
      report += `- **${reason}:** ${count}\n`
    }
  }

  report += `\n---\n\n> Generated by \`scripts/audit-listing-visibility.mjs\` (Task 454, Epic LV). Read-only — zero DB writes.\n`

  writeFileSync(reportPath, report, 'utf8')
  console.log(`Report written to ${reportPath}`)
  console.log(`  Total eligible: ${(listings ?? []).length}`)
  console.log(`  Hidden: ${hidden.length}`)
  if (hidden.length > 0) {
    const byReason = {}
    for (const h of hidden) {
      byReason[h.reason] = (byReason[h.reason] ?? 0) + 1
    }
    for (const [reason, count] of Object.entries(byReason)) {
      console.log(`    ${reason}: ${count}`)
    }
  }
}

// Only run the audit when invoked directly (node scripts/audit-listing-visibility.mjs).
// Importing this module for its exports does NOT execute main().
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    console.error('Audit script failed:', err)
    process.exit(1)
  })
}
